import { chromium } from 'playwright';
import { createServer } from 'vite';
import { tmpdir } from 'node:os';
import { resolve } from 'node:path';
const root = resolve(import.meta.dirname, '..');
const vite = await createServer({ root, logLevel: 'error', cacheDir: resolve(tmpdir(), 'hv-dbg-' + process.pid), server: { port: 0, host: '127.0.0.1', hmr: false, watch: null } });
await vite.listen();
const port = vite.httpServer.address().port;
const browser = await chromium.launch({ headless: true, args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist'] });
const page = await (await browser.newContext({ viewport: { width: 960, height: 540 } })).newPage();
page.on('console', (m) => console.log('[pg]', m.text()));
await page.goto(`http://127.0.0.1:${port}/?notitle=1&map=farm&x=30.5&z=22.5&time=9`, { timeout: 180000 });
await page.waitForFunction(() => typeof window.__game?.ready === 'function', null, { timeout: 180000 });
await page.evaluate(() => window.__game.ready());
const T = await page.evaluate(() => {
  const g = window.__game.game.services.net.sync.grid();
  for (let z = 24; z < 34; z++) for (let x = 34; x < 50; x++) if (g.hasFlag(x, z, 2) && !g.hasFlag(x, z, 4) && !g.getObject(x, z) && !g.hasFlag(x, z, 1) && g.isWalkable(x, z + 1)) return { x, z };
});
console.log('T', T);
await page.evaluate((t) => { window.__game.teleport('farm', t.x + 0.5, t.z + 1.5); window.__game.facing('up'); }, T);
await new Promise((r) => setTimeout(r, 500));
await page.keyboard.press('Digit1'); await page.keyboard.press('KeyC');
await new Promise((r) => setTimeout(r, 1800));
const st = () => page.evaluate((t) => { const s = window.__game.game.services.net.sync; const g = s.grid(); return s.digest().get(g.idx(t.x, t.z)) ?? ''; }, T);
console.log('after hoe', await st());
await page.evaluate((t) => { window.__game.teleport('farm', t.x - 0.5, t.z + 0.5); window.__game.facing('right'); }, T);
await new Promise((r) => setTimeout(r, 400));
await page.keyboard.press('Digit2');
console.log('sel', await page.evaluate(() => [window.__game.game.services.inventory.selected(), window.__game.game.services.farming.canInfo?.() , window.__game.game.player.facing, window.__game.game.player.targetTile(), window.__game.game.input.pointer]));
await page.keyboard.press('KeyC');
await new Promise((r) => setTimeout(r, 1900));
console.log('after water', await st());
await browser.close(); await vite.close();
